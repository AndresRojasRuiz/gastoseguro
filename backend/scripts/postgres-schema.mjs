#!/usr/bin/env node
/**
 * Genera prisma/postgres/schema.prisma a partir del esquema de desarrollo (SQLite), de modo
 * que exista una única fuente de verdad del modelo de datos. Después crea (si no existe) la
 * migración inicial de PostgreSQL sin necesidad de un servidor de base de datos.
 *
 * Uso: npm run db:postgres-schema -w backend
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const backend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(backend, 'prisma', 'schema.prisma');
const targetDir = path.join(backend, 'prisma', 'postgres');
const target = path.join(targetDir, 'schema.prisma');

const schema = readFileSync(source, 'utf8')
  .replace('provider = "sqlite"', 'provider = "postgresql"')
  .replace('output              = "../src/generated/prisma"', 'output              = "../../src/generated/prisma"');

if (!schema.includes('provider = "postgresql"') || !schema.includes('../../src/generated/prisma')) {
  console.error('No se pudo adaptar el esquema: revisa el bloque datasource/generator.');
  process.exit(1);
}

mkdirSync(targetDir, { recursive: true });
writeFileSync(target, `// FICHERO GENERADO por scripts/postgres-schema.mjs: no editar a mano.\n${schema}`);
console.log(`Esquema PostgreSQL generado en ${path.relative(backend, target)}`);

const migrationsDir = path.join(targetDir, 'migrations');
const initDir = path.join(migrationsDir, '20261014000000_init');
if (!existsSync(initDir)) {
  mkdirSync(initDir, { recursive: true });
  // Se invoca la CLI de Prisma con el propio Node y sin shell: los argumentos no se interpretan.
  const prismaCli = path.join(path.dirname(createRequire(import.meta.url).resolve('prisma/package.json')), 'build', 'index.js');
  const sql = execFileSync(process.execPath, [prismaCli, 'migrate', 'diff', '--from-empty', '--to-schema', target, '--script'], {
    cwd: backend,
    encoding: 'utf8',
    env: { ...process.env, DB_PROVIDER: 'postgresql', DATABASE_URL: process.env.DATABASE_URL ?? 'postgresql://placeholder@localhost:5432/placeholder' },
  });
  writeFileSync(path.join(initDir, 'migration.sql'), sql);
  writeFileSync(path.join(migrationsDir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n');
  console.log(`Migración inicial creada en ${path.relative(backend, initDir)}`);
}
